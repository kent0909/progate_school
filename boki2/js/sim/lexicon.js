// 言葉の関所。画面に出る会計用語・書類用語を見つけ、まだ教えていない言葉を検出する。
// ブラウザ（検定ミニで解ける問題だけを選ぶ）と tools/lexicon-check.js（台本の検査）の両方で使う。
(function (g) {
  const B = (g.BOKI = g.BOKI || {});
  const L = (B.lex = {});
  // 会計の概念語（勘定科目は accounts.js の全キーを自動で加える）
  L.concepts = ['資産', '負債', '純資産', '収益', '費用', '帳簿', '記帳', '仕訳', '借方', '貸方', '試算表', '決算', '決算書', '貸借対照表', '損益計算書',
    '掛け', '取得原価', '付随費用', '三分法', '発生主義', '実現', '定額法', '定率法', '間接法', '直接法', '耐用年数', '残存価額', '差額補充法', '評価勘定', '帳簿価額',
    '監査', '融資', '与信', '配当', '株主', '出資', '引当', '償却', '売上原価', '原価', '自動仕訳', '勘定', '期末', '期首', '当期', '前期', '月割', '銀行勘定調整表', '黒字倒産', '払込', '払込額', '小切手', '手形', '約束手形', '残高証明書', '税抜', '消費税', '生産高比例法', '売上原価対立法', '分記法', '資本的支出', '収益的支出', '据付費', '試運転費', '改定償却率', '保証率', '償却率', '圧縮記帳', '建設仮勘定', '割賦', 'リース', '為替', '有価証券', '連結', '税効果'];
  // 書類にだけ出る言葉。書類の上では、タップすると一言の説明が出る
  L.docWords = {
    '普通預金 通帳': 'いつでも出し入れできる銀行口座の通帳',
    摘要: '何のお金かを書いたメモ欄',
    お預け入れ: '口座にお金が入ったこと',
    お引出し: '口座からお金が出ていったこと',
    品名: '買った・売ったものの名前',
    お支払期日: 'この日までに払ってね、という約束の日',
    '請求書（控え）': '自分が出した請求書のコピー',
    棚卸表: '倉庫の商品を数えた表',
    固定資産台帳: '長く使うもの（トラックなど）の一覧',
    監査メモ: '森さんが調べた結果のメモ',
    レジ締め日報: '1日の終わりにレジのお金を数えた記録',
  };
  // 日常語として許す（勘定科目と同じ字でも、ふだんの言葉として通じるもの）
  L.everyday = ['商品', '材料', '現金', '給料', '手数料', '借金', '残高', '利息', '銀行', '通帳', '請求書', '振込', '値引き', '在庫', '倉庫', 'トラック', '会社', '社長', '株', '保険', '税金', '土地', '建物'];
  L.terms = () => {
    if (L._terms) return L._terms;
    const all = new Set([...Object.keys(B.accounts || {}), ...L.concepts, ...Object.keys(L.docWords)]);
    L.everyday.forEach((w) => all.delete(w));
    return (L._terms = [...all].sort((a, b) => b.length - a.length));
  };
  // text に出てくる用語（最長一致。「仕入れる」のような動詞は除く）
  L.scan = (text) => {
    let t = String(text || '').replace(/<[^>]+>/g, ' ');
    const found = new Set();
    for (const w of L.terms()) {
      let i = t.indexOf(w);
      while (i >= 0) {
        const after = t[i + w.length];
        const verb = (w === '仕入' && after === 'れ') || (w === '売上' && after === 'げ');
        if (!verb) found.add(w);
        t = t.slice(0, i) + '□'.repeat(w.length) + t.slice(i + w.length);
        i = t.indexOf(w, i + w.length);
      }
    }
    return [...found];
  };
  L.unknown = (text, taught) => L.scan(text).filter((w) => !taught.has(w));
})(typeof window !== 'undefined' ? window : globalThis);
