#!/usr/bin/env python3
# BIZ-MKT-RAMEN 8章の CPA／LTV の計算（版1.1。論証検査 K10・K66・K68 の直し）。
# 前提の値はすべて報告 8.1 の表のとおり（客単価・原価率は原文、f・m・r・反応率は置き値）。
# Usage: python3 boki2/docs/analysis/bizmkt-ramen-cpa.py
import itertools

S = {  # 下・中・上の前提（f は「1店への」来店頻度の置き値。全体への頻度の平均1.81回/月より小さく置く）
    '下': dict(g=600, f=0.5, m=12, r=0.10),
    '中': dict(g=650, f=1.0, m=18, r=0.25),
    '上': dict(g=700, f=1.5, m=24, r=0.40),
}
LEMON = dict(g=200, f=4.0)  # BIZ-MKT のレモネードの例（粗利200円、常連は月4杯）


def ltv(g, f, m, r):
    reg = g * f * m
    return reg, g + r * reg


print('== 1. 常連1人と新規1人の期待 LTV（粗利） ==')
rows = {}
for k, p in S.items():
    reg, new = ltv(**p)
    lreg, lnew = ltv(LEMON['g'], LEMON['f'], p['m'], p['r'])
    rows[k] = (reg, new, lnew)
    print(f"{k}: ラーメン 常連 {reg:,.0f}円 = {p['g']}×{p['f']}×{p['m']} ／ 新規 {new:,.0f}円 = {p['g']}＋{p['r']}×{reg:,.0f}"
          f" ｜ 同じ r・m のレモネード 新規 {lnew:,.0f}円 = 200＋{p['r']}×(200×4×{p['m']}) ｜ 比 {new / lnew:.2f}")
print('BIZ-MKT 自身のレモネードの例：200＋0.33×(200×4×12)＝3,368円')

print('\n== 2. 打ち手ごとの「元が取れる新規の数」（費用÷新規1人の期待 LTV） ==')
COST = {
    'ポスティング3,000部（配布・印刷2.1万円、デザインは自作0円）': 21000,
    'ポスティング3,000部（配布・印刷2.1万円＋デザイン相場の下端2万円）': 41000,
    'グルメサイト有料・平均（月）': 23100,
    'グルメサイト有料・最安（月）': 10000,
    'インフルエンサー1万人（2円）': 20000,
    'インフルエンサー1万人（6円）': 60000,
    'SNS 広告（5ドル×6日）': 4500,
}
for name, c in COST.items():
    parts = []
    for k in S:
        parts.append(f"{k} {c / rows[k][1]:.1f}人（レモネード {c / rows[k][2]:.1f}人）")
    print(f"{name} {c:,}円：1回で元が取れる来店 {c / 650:.1f}（g=650）／" + '・'.join(parts))

print('\n== 3. ポスティングで元が取れる反応率（部数3,000） ==')
for c in (21000, 41000):
    for k in S:
        n = c / rows[k][1]
        print(f"費用 {c:,}円・{k}：新規 {n:.1f}人 → 反応率 {n / 3000 * 100:.2f}%")

print('\n== 4. 置き値の格子（g×f×m×r×反応率×費用）で、ポスティングが元を取る組の割合 ==')
G = [600, 650, 700]
F = [0.5, 1.0, 1.5]
M = [12, 18, 24]
R = [0.10, 0.20, 0.30, 0.40]
RESP = [0.0005, 0.001, 0.002, 0.003]  # 0.05〜0.3%（業者の目安の幅。報告では使わないとした置き値）
C = [21000, 41000]
tot = ok = 0
lem_ok = 0
for g, f, m, r, q, c in itertools.product(G, F, M, R, RESP, C):
    tot += 1
    _, new = ltv(g, f, m, r)
    if 3000 * q * new >= c:
        ok += 1
    _, lnew = ltv(200, 4.0, m, r)
    if 3000 * q * lnew >= c:
        lem_ok += 1
print(f"組の数 {tot}：ラーメンで元が取れる {ok}（{ok / tot * 100:.0f}%）・同じ格子のレモネード {lem_ok}（{lem_ok / tot * 100:.0f}%）")

print('\n== 5. そのほか ==')
print(f"100円引き（1,000円の一杯、粗利650→550円）：同じ粗利に戻すには来店 {650 / 550:.3f} 倍。レモネード 200→150円は {200 / 150:.3f} 倍")
print(f"フェスの売れ残り：(2,000−850)杯×300〜330円＝{1150 * 300:,}〜{1150 * 330:,}円【推論：原価率30〜33%×1杯1,000円】")
print(f"1回の粗利のレモネードとの比：{600 / 200:.1f}〜{700 / 200:.1f} 倍")
print(f"BIZ-MKT 自身のレモネードの例：新規6人×200円＋常連2人×9,600円＝{6 * 200 + 2 * 9600:,}円 対 費用21,000円 → 回収率 {(6 * 200 + 2 * 9600) / 21000 * 100:.0f}%")
DAY = 84.7  # 中華そば（ラーメン）店の1日平均客数（厚労省の実態調査）
MONTH = DAY * 26
for k in S:
    n = 21000 / rows[k][1]
    print(f"ポスティング2.1万円・{k}：元が取れる新規 {n:.1f}人 ＝ 1日84.7人×26日（月 {MONTH:,.0f}人）の {n / MONTH * 100:.2f}%")
print("ポスティングの配布数は区域の世帯の4〜7割（業者の設定）→ 3,000部を配る区域の世帯は約 "
      f"{3000 / 0.7:,.0f}〜{3000 / 0.4:,.0f}世帯")

print('\n== 6. 格子の感度（版1.2。論証検査16.5の7通りを同じ式で再現） ==')


def grid(F_=F, RESP_=RESP, lem_cups=4.0):
    tot = ok = lok = 0
    for g, f, m, r, q, c in itertools.product(G, F_, M, R, RESP_, C):
        tot += 1
        if 3000 * q * ltv(g, f, m, r)[1] >= c:
            ok += 1
        if 3000 * q * ltv(200, lem_cups, m, r)[1] >= c:
            lok += 1
    return tot, ok, lok


VAR = [
    ('報告のまま（f 0.5/1/1.5・反応率0.05〜0.3%・レモネード月4杯）', {}),
    ('レモネードを月2杯', dict(lem_cups=2.0)),
    ('レモネードを月6杯', dict(lem_cups=6.0)),
    ('ラーメンの f の上を全体への平均1.8回', dict(F_=[0.5, 1.0, 1.8])),
    ('反応率0.1〜0.5%', dict(RESP_=[0.001, 0.002, 0.003, 0.005])),
    ('反応率0.3〜1.0%', dict(RESP_=[0.003, 0.005, 0.007, 0.010])),
    ('反応率0.01〜0.1%', dict(RESP_=[0.0001, 0.0003, 0.0005, 0.001])),
]
for name, kw in VAR:
    tot, ok, lok = grid(**kw)
    print(f"{name}：{tot}組、ラーメン {ok}（{ok / tot * 100:.0f}%）・レモネード {lok}（{lok / tot * 100:.0f}%）")
for f in (0.5, 1.0, 1.5, 1.8):
    print(f"常連1人の月の粗利：ラーメン f={f} は {650 * f:.0f}円、レモネード月4杯は800円（比 {650 * f / 800:.2f}）")
