#!/usr/bin/env python3
"""地域の採算（BIZ-FILL-RAMEN「地域の採算の表」）。オーナーの指摘「銀座だと100杯でも赤字、奥多摩なら30杯でも採算」を、
資料のある数と【推論】の数を分けて試算する。
資料の数（出典は BIZ-FILL-RAMEN の表）：
  ・中華そば（外食）1杯の値段：小売物価統計 2026年7月（81市）  → 引数の xlsx から読む
  ・民営家賃（住宅、3.3㎡・月）：同上
  ・飲食店の募集賃料：銀座 42,497円/坪（飲食店ドットコム 2025下期）、東京9エリア飲食店可 30,227円/坪・銀座 36,250円/坪（アットホーム 2025下期）
  ・最低賃金：東京 1,280円、最低の県 1,085円（令和8年度）
  ・元店主の試算の型：1杯1,000円×40杯×25日、原価30%、アルバイト10万円、光熱・家賃・その他40万円、税・保険3万円、返済5万円（石動龍）
【推論】の数（資料がない）：店の広さ10坪、銀座で100杯を回す人数と時間、奥多摩の賃料、営業日数、光熱その他。
使い方: python3 -I boki2/docs/analysis/fill-region.py <小売物価 第1部の xlsx> <小売物価 第2部の xlsx>
"""
import sys, statistics, openpyxl
def row(f, key):
    ws = openpyxl.load_workbook(f, read_only=True).worksheets[0]
    rows = list(ws.iter_rows(values_only=True))
    hdr = [r for r in rows if r and any(str(x) == '札幌市' for x in r)][0]
    r = [r for r in rows if r and any(str(x).startswith(key) for x in r if x)][0]
    i = [str(x) for x in hdr].index('札幌市')
    return {hdr[j]: r[j] for j in range(i, len(hdr)) if hdr[j] and isinstance(r[j], (int, float))}
price = row(sys.argv[1], '中華そば(外食)'); rent = row(sys.argv[2], '民営家賃')
def summary(d, name, unit):
    v = sorted(d.values()); lo = min(d, key=d.get); hi = max(d, key=d.get)
    print(f'{name}: {len(v)}市、中央値{statistics.median(v):.0f}{unit}、最低 {lo} {d[lo]}{unit}、最高 {hi} {d[hi]}{unit}、最高÷最低 {d[hi]/d[lo]:.2f}')
summary(price, '中華そば1杯', '円'); summary(rent, '民営家賃3.3㎡', '円')
for c in ('東京都区部', '八王子市', '立川市', '府中市', '札幌市', '山形市', '福岡市', '大阪市', '名古屋市', '横浜市', '八戸市', '函館市'):
    print(f'  {c}: 中華そば {price.get(c)}円・民営家賃 {rent.get(c)}円')
print(f'民営家賃 区部÷八戸 = {rent["東京都区部"]}/{rent["八戸市"]} = {rent["東京都区部"]/rent["八戸市"]:.2f}')
print(f'最低賃金 東京÷最低の県 = 1280/1085 = {1280/1085:.2f}')

# 損益分岐の杯数： 1日の杯数 = (固定費 + 店主の取り分) / (営業日数 × 1杯の値段 × (1 − 原価率))
def cups(fixed, owner, price, days=25, cost=0.30):
    return (fixed + owner) / (days * price * (1 - cost))
print('\n元店主の型の検算：40杯×1,000円×25日 = ', 40*1000*25, '円。残り = 100万 −30万 −10万 −40万 −3万 −5万 =', 1000000-300000-100000-400000-30000-50000)
print('\n| 場所 | 1杯の値段 | 家賃（月） | 人件費（月） | その他の固定費（月） | 返済・税保険（月） | 店主0円で分岐の杯数 | 店主30万円で分岐の杯数 | 100杯の月の残り | 30杯の月の残り | どの数が資料か |')
print('|---|---|---|---|---|---|---|---|---|---|---|')
cases = [
 # 名, 値段, 家賃, 人件費, その他, 返済税, 根拠のメモ
 ('銀座（値段は区部の統計）', price['東京都区部'], 42497*10, 1280*8*25*3, 250000, 80000, '値段＝区部617円[一]、家賃＝坪42,497円[実]×10坪【推論】、人＝最低賃金1,280円[一]×8時間×25日×3人【推論】、その他25万【推論】'),
 ('銀座（値段1,000円）', 1000, 42497*10, 1280*8*25*3, 250000, 80000, '値段1,000円【推論：TSRの「1,000円超えが珍しくない」】、他は同上'),
 ('銀座（値段1,300円）', 1300, 42497*10, 1280*8*25*3, 250000, 80000, '値段1,300円【推論】、他は同上'),
 ('都心9エリアの中央（アットホーム）', 1000, 30227*10, 1280*8*25*2, 200000, 80000, '家賃＝坪30,227円[実]×10坪【推論】、人2人【推論】'),
 ('奥多摩（家賃は低い想定）', price['八王子市'], 60000, 1280*6*25*1, 200000, 80000, '値段＝八王子890円[一]を近い市の値として【推論】、家賃6万【推論】、人1人＋店主【推論】'),
 ('元店主の地方の型', 1000, 0, 100000, 400000, 80000, '石動龍の型[作]（家賃は「光熱・家賃・その他40万」の中）'),
]
for name, p, r, l, o, debt, memo in cases:
    fixed = r + l + o + debt
    c0 = cups(fixed, 0, p); c30 = cups(fixed, 300000, p)
    m100 = 100*25*p*0.7 - fixed; m30 = 30*25*p*0.7 - fixed
    print(f'| {name} | {p:,.0f}円 | {r:,.0f}円 | {l:,.0f}円 | {o:,.0f}円 | {debt:,.0f}円 | {c0:.0f} | {c30:.0f} | {m100:+,.0f}円 | {m30:+,.0f}円 | {memo} |')
print('\n（100杯・30杯の月の残りは、店主の取り分の前。原価率30%、25日営業。人件費は杯数で変えていない＝100杯を3人で回せる前提【推論】）')
