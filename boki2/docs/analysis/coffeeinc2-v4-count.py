# ---- 3. 8章のライバルの決算書の例の検算（単位：百万円。仮置きの数） ----
print('\n3. ライバルの決算書の例の検算（単位：百万円、仮置き）')
S3 = 160.0                       # 3年目の年商（4店）
debt = S3 * 8 / 12               # 借入＝月商の8か月分
op3 = S3 * 0.02                  # 営業利益率2%
dep_rate = 0.03                  # 減価償却＝年商の3%（仮置き）
dep = S3 * dep_rate
for r in (0.02, 0.03):
    cf = op3 + dep - debt * r
    print('  3年目：営業利益 %.1f＋減価償却 %.1f−支払利息 %.1f（金利%.0f%%）＝営業CF の近似 %.1f' % (op3, dep, debt * r, r * 100, cf))
need = (op3 + dep) / debt
print('  売上が変わらないまま利息だけで営業CF を赤字にするのに要る金利：%.1f%%（減価償却3%%のとき。2%%なら %.1f%%、4%%なら %.1f%%）' % (
    need * 100, (op3 + S3 * 0.02) / debt * 100, (op3 + S3 * 0.04) / debt * 100))
drop, mr = 0.12, 0.60            # 4年目：近くに安売りチェーンが出て売上−12%、限界利益率60%（仮置き）
S4 = S3 * (1 - drop)
op4 = op3 - S3 * drop * mr
for r in (0.02, 0.03):
    cf4 = op4 + dep - debt * r
    print('  4年目：売上 %.1f（−%.0f%%）→営業利益 %.1f−%.1f×%.0f%%＝%.1f、営業CF の近似 %.1f＋%.1f−%.1f（金利%.0f%%）＝%.1f' % (
        S4, drop * 100, op3, S3 * drop, mr * 100, op4, op4, dep, debt * r, r * 100, cf4))
print('  （利息を財務の区分に入れる会社なら、利息を引く前の営業CF は %.1f。売上の落ち込みだけで赤字になる）' % (op4 + dep))
