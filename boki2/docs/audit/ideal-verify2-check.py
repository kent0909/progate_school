for l in R:
    m = re.match(r'\| ?([A-Z]+\d+) ?\|', l)
    if m:
        c = [x.strip() for x in l.split('|')[1:-1]]
        if len(c) >= 6 and c[5] in ('弱い', '不当'): weak.append(c[0])
got = [r[1][2:] for r in rows if r[1].startswith('R-')]
print('検査書の弱い・不当:', len(weak), ' 対応表の R-:', len(got), ' 抜け:', sorted(set(weak) - set(got)), ' 余り:', sorted(set(got) - set(weak)))

